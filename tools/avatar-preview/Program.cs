using System;
using System.Globalization;
using System.IO;
using System.Text;
using IronNestCoop.Sync;
using G = IronNestCoop.Sync.AvatarGeometry;

// Writes window.AVATAR = { parts, colors, rig } as a script next to docs/avatar/preview.html,
// so the preview opens from disk without a server.
static string F(float v) => v.ToString("0.####", CultureInfo.InvariantCulture);
static string V(G.V3 v) => $"[{F(v.X)},{F(v.Y)},{F(v.Z)}]";

string outPath = args.Length > 0 ? args[0] : Path.Combine("docs", "avatar", "geometry.js");
var parts = G.BuildAll();
var sb = new StringBuilder("// generated by tools/avatar-preview from AvatarGeometry.cs; do not edit\nwindow.AVATAR = {\n parts: {\n");
int total = 0;
foreach (var p in parts)
{
    total += p.Triangles;
    sb.Append($"  {p.Name}: {{ subs: [");
    foreach (var s in p.Subs)
    {
        sb.Append($"{{ mat: {s.Material}, tris: [");
        // flat shaded: each index is its own vertex, so the triangles are runs of three
        for (int i = 0; i < s.Tris.Count; i++) { if (i > 0) sb.Append(','); var v = p.Pos[s.Tris[i]]; sb.Append($"{F(v.X)},{F(v.Y)},{F(v.Z)}"); }
        sb.Append("] }, ");
    }
    sb.Append("] },\n");
}
sb.Append(" },\n colors: [");
foreach (var c in G.Colors) sb.Append($"[{F(c[0])},{F(c[1])},{F(c[2])}],");
sb.Append("],\n rig: { ");
sb.Append($"hipY: {F(G.HipY)}, hipYCrouch: {F(G.HipYCrouch)}, hipX: {F(G.HipX)}, neckY: {F(G.NeckY)}, shoulderX: {F(G.ShoulderX)}, shoulderY: {F(G.ShoulderY)}, ");
sb.Append($"tailY: {F(G.TailY)}, tailZ: {F(G.TailZ)}, headScale: {F(G.HeadScale)}, head: {V(G.HeadOffset)}, helmet: {V(G.HelmetOffset)}, eyes: {V(G.EyesOffset)} }},\n");
sb.Append($" triangles: {total}\n}};\n");
File.WriteAllText(outPath, sb.ToString());
Console.WriteLine($"{outPath}: {parts.Length} parts, {total} triangles");
foreach (var p in parts) Console.WriteLine($"  {p.Name,-7} {p.Triangles,4} tris, {p.Subs.Count} materials");
